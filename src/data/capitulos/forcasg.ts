// M1V7 - I · Eixos G
// - 1 G = aceleração da gravidade (32 ft/s²); eixos Gz (+Gz cabeça→pés, em puxadas e loops; −Gz pés→cabeça, em
//   mergulhos picados), Gx (peito-costas: decolagem e frenagem), Gy (ombro a ombro: rolamentos); caças e aviões
//   acrobáticos chegam a 9 G; catapulta leva a mais de 160 mph em menos de 2 s; pilotos civis podem se surpreender
//   com G alto em curvas fechadas e na recuperação de atitudes anormais; a maioria dos aviões civis não tem traje
//   anti-G: FAA CAMI, Acceleration in Aviation: G-Force (OK-21-0375, 14 dez. 2021).
// - Fator de carga numa curva nivelada n = 1 ÷ cos(inclinação): física do voo (60° → 2 G).
// - Limites de manobra: transporte (14 CFR 25.337(b)–(c)) +2,5 G no mínimo, até 3,8; −1,0 G até VC. Aviões leves
//   (14 CFR 23.337, edição 2011): normal até 3,8; utilidade 4,4; acrobática 6,0; negativos de 0,4 (normal e utilidade)
//   e 0,5 (acrobática) vezes o positivo. Peso aparente = massa × G (cálculo).
// M1V7 - II · G-LOC e A-LOC
// - Queda hidrostática da pressão no nível dos olhos de cerca de 22 mmHg por G, se a pressão no coração se mantiver:
//   Pollock RD et al. Aerosp Med Hum Perform 2019;90(11):925-33.
// - Ordem dos sintomas em +Gz (visão em túnel, acinzentamento, apagamento, G-LOC); início gradual (≈ 0,1 G/s) dá aviso
//   visual; início rápido (≥ 1 G/s) pode causar G-LOC sem aviso; −Gz: sangue represado na cabeça, "red out" e
//   inconsciência rápida; fatores: desidratação, fadiga, fome, medicamentos, sedentarismo e fumo: FAA OK-21-0375.
// - Limiares: perda periférica da visão 3,4–4,8 G; apagamento 4–5,6 G; inconsciência 4,5–6,3 G; reflexo barorreceptor
//   ≈ 6–9 s; reserva de oxigênio do cérebro ≈ 4–6 s; abalos mioclônicos ≈ 4 s depois do retorno do fluxo;
//   incapacitação absoluta ≈ 11,9 s (2–38) e relativa ≈ 16 s (2–97), total ≈ 28 s (500 indivíduos em centrífuga);
//   cerca de 20 mortes na Força Aérea dos EUA atribuídas a G-LOC; menos de 600 h no tipo, menos de 30 anos e manobra
//   mal feita em 72% dos acidentes por G-LOC (Sevilla e Gardner): StatPearls, Aerospace Gravitational Effects
//   (ed. Chumbley E, atualizado em 8 ago. 2023).
// - Mais de 700 casos estudados; inconsciência ≈ 12 s e desorientação ≈ 12 s depois; sonhos curtos ("dreamlets"):
//   Whinnery JE, entrevista em TCU Magazine, 2008.
// - Efeito "push-pull" (G negativo antes do positivo reduz a tolerância): fator em 12% a 31% dos incidentes nas
//   pesquisas; cerca de 10% no levantamento britânico; A-LOC e G-LOC: Jones M-L et al. Aerosp Med Hum Perform
//   2026;97(4):257-63.
// M1V7 - III · Manobra anti-G
// - Tolerância relaxada sem traje, início gradual: média 4,37 G (3,21–5,97), 29 voluntários: Gowda A et al. Ind J
//   Aerospace Med 2013;57(2):9-13. 4,4 ± 0,6 G; manobra treinada ≈ 3,0 G de proteção (7,3 G total); só contrair ≈ 2,1 G;
//   traje bem ajustado ≈ 1 G; "4 + 1 + 4 = 9 G" como estimativa; contração isométrica de pernas, abdômen e braços,
//   esforço contra a glote fechada por 3 a 4 s e inspiração rápida: Renjhen P, Agarwal A. Ind J Aerospace Med
//   2011;55(1):35-8.
// - Traje de cobertura total: tolerância relaxada média 6,2 G; evita 64% da queda de pressão no olho no início
//   gradual (59% no rápido); traje parcial 48%: Pollock 2019.
// - Não fazer a manobra com 100% de esforço a 1 G; hidratação, descanso, condicionamento aeróbico e resistido,
//   aquecimento de G: FAA OK-21-0375.
